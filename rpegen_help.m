function [heading,body] = rpegen_help(topic)
% Contextual definitions shared by the main app's help window and tests.
heading = ['RpEGEN Help: ' char(topic)];
switch char(topic)
    case 'Setup'
        body = {
            'SETUP'
            'Analyze one treatment group at a time. Each animal contributes one independent eye.'
            ''
            'ROI folder / Image folder: matching individual ImageJ ROI and 8-bit grayscale TIFF files. Brightfield page selects the TIFF page, not an intensity value.'
            'Group name: the MATLAB variable and output MAT filename. Output folder receives the group MAT, run record, and sample QC PDFs.'
            ''
            'Check Inputs: checks matching names, ROI type/bounds/area, image type, and TIFF page. It does not run extraction or decide whether the anatomy is correctly outlined.'
            'Example Data: fills in input paths and checks them. It does not load analyzed eyes into QC.'
            'Run Analysis: extracts intensities and centerlines and saves results. Replace overwrites this group MAT and matching QC PDFs, not source images or ROIs.'
            'Open Existing Results: loads a full group MAT into QC and Results. No extraction rerun is needed.'
            ''
            'Compare Groups also loads saved group MATs independently.'
            'After a code update, close and relaunch RpEGEN_GUI. An already-open GUI retains its earlier callbacks.'};
    case 'Quality Control'
        body = {
            'QUALITY CONTROL'
            'Review the image, ROI boundary, centerline, angular assignment, and intensity profile for each eye.'
            ''
            'Angles run from 0 (dorsal) to 180 degrees (ventral). Intensity is 0 (black) to 255 (white).'
            'The profile shows local brightness along this eye. At each centerline point, we take the median (middle value) of its assigned pixel intensities.'
            ''
            'Left Arrow selects the previous eye; Right Arrow selects the next. The adjacent buttons and Page Up / Page Down also work. Navigation stops at the first and last eye. The dropdown selects an eye directly. While an input control is selected, arrow keys retain their normal editing or selection behavior; click an image or navigation button to resume eye navigation.'
            'On macOS, Show QC PDF in Finder selects the original file; double-click it in Finder to open it.'
            'Export PDFs regenerates QC PDFs for every eye in this loaded group from saved data, without rerunning extraction. Choose a folder and confirm before replacing existing PDFs.'
            'PDFs show the same brightfield overlays and intensity profile as this viewer. All three image panels have matching colorbar space and show the same full image extent.'
            ''
            'QC requires Setup > Run Analysis or Open Existing Results. Loading only Compare Groups does not populate this tab.'
            'This viewer does not edit ROIs or record pass/fail exclusions. Correct an ROI in ImageJ/FIJI and rerun extraction for the affected group.'};
    case 'Results'
        body = {
            'RESULTS TABLE'
            'Each row summarizes one angular slice, such as 40-45 degrees, for the current Setup group. We combine (pool) the pixels from all eyes within that slice.'
            ''
            'Group: treatment/group label.'
            'Angle: center of the angular bin, in degrees.'
            'Numel: number of pixels contributing to this row.'
            'Mean: average pixel intensity.'
            'Median: middle intensity after sorting; for an even count, average the two middle values. Example: 10, 20, 90 have mean 40 but median 20.'
            'STD (standard deviation): how much pixel brightness varies. Larger values mean a wider spread.'
            'SE (standard error): how precisely the MEAN is estimated when treating pixels as independent. It is STD / sqrt(Numel); STD = 20 and Numel = 100 gives SE = 2.'
            'CI95L / CI95U: the lower and upper ends of the pixel-based 95% confidence interval for the MEDIAN. A narrower interval means a more precisely defined median under this method.'
            ''
            'KEEP IN MIND'
            'Eyes supplying more pixels have more weight. The pixel-based uncertainty calculations treat pixels as independent, although pixels from one eye are related. For uncertainty across eyes, see the whole-eye bootstrap in Compare Groups > Median Profiles.'
            ''
            'The bin selector changes the displayed saved table. Export Binned CSVs writes all three tables (1, 5, and 10 degrees).'
            'Original intensity bins exclude the upper edge, including exactly 180 degrees in the final bin.'};
    case 'Heatmaps'
        body = {
            'COMPARE GROUPS / HEATMAPS'
            'Add Groups loads one group per MAT file. Example Groups adds the four precomputed example groups. Add Current Results adds the group loaded in Setup.'
            'Loading Groups appears immediately while files and plots are prepared, including bootstrap confidence bands. Loading buttons are disabled until it finishes; no second click is needed.'
            'Show controls which groups appear in descriptive plots, not which groups are available for a permutation test. Animals / eyes counts saved eye IDs.'
            'Remove Selected removes table entries only; it does not delete files.'
            ''
            'Angle bin: angular interval for the heatmap and median profiles (1, 5, or 10 degrees).'
            'Intensity bin: intensity interval for heatmaps only (1, 5, or 15).'
            'Pixel count: number of pixels in each angle/intensity cell.'
            'Percent per angle: the percentage of pixels in each brightness range. Example: 200 of 1,000 pixels gives 20%. Each nonempty angular column adds up to 100%.'
            'Use the heatmap to see the spread of brightness at each angle. Eyes contributing more pixels have more weight. Use Median Profiles for uncertainty in the median and Permutation Test for p-values.'
            'Shown groups share a color scale. Changing the groups can change that scale. Heatmaps include exactly 180 degrees and intensity 255 in the final bins.'
            ''
            'Export Figure saves a vector PDF; the heatmap image layer remains raster.'};
    case 'Median Profiles'
        body = {
            'MEDIAN PROFILES'
            'The line shows the group median. Both confidence bands describe how precisely that SAME median is defined, but they answer different questions.'
            ''
            'THE MEDIAN LINE'
            'Within each angular slice, such as 40-45 degrees, combine all pixel intensities from the group and take the middle value. That is the pooled median. Eyes contributing more pixels have more weight.'
            ''
            'PIXEL-BASED MEDIAN CI (DARK)'
            'How well do these pixels define the median?'
            'If 10 eyes provide 1,000 pixels, this calculation treats those as 1,000 independent observations. Many pixels can give a very narrow band. This is the original CI calculation.'
            ''
            'WHOLE-EYE BOOTSTRAP CI (LIGHT)'
            'How much might the median change with a different sample of eyes?'
            'This calculation treats the example as 10 independent eyes and keeps each eye''s pixels together. Bootstrap means repeatedly drawing from the eyes we already have, allowing repeats.'
            'With eyes A, B, C, one draw could be A, A, C. We recalculate the pooled median for 5,000 draws of the same group size. The band spans the middle 95% of those medians.'
            'Pixels stay at their original angles: the 40-45 degree bin uses only 40-45 degree pixels. The same eye draw is used at every angle.'
            ''
            'HOW TO READ BOTH BANDS'
            'CI means confidence interval: an uncertainty band around the estimated median. For example, a median of 100 with a CI of 90-110 shows an estimate of 100 with uncertainty extending from 90 to 110. Pixel intensities themselves can vary much more widely.'
            '95% is the intended coverage: over many repeated studies, a well-calibrated method would cover the underlying median about 95% of the time.'
            'Use the bootstrap as your main guide to how well the group median is defined across eyes. The pixel-based band shows precision when treating each pixel separately.'
            ''
            'KEEP IN MIND'
            'Pixels within an eye are related, so the pixel-based band can look overly precise. The bootstrap relies on independent eyes and is less reliable with very few eyes; shared wells or batches are not accounted for. Each band applies separately at each angle. Gaps mean there is insufficient usable data for that interval.'
            'Overlapping or separated bands alone do not establish whether treatments differ significantly.'
            ''
            'DISPLAY AND EXPORTS'
            'Legend n counts eyes. Check either band on or off; the median and permutation results stay the same.'
            'Export Figure preserves the checked bands in a vector PDF. Keep the MAT data to regenerate the plot.'};
    case 'Permutation Test'
        body = {
            'PERMUTATION TEST'
            'Do the two groups have different median intensities at this angle? This test checks how unusual the observed difference is when pixels are randomly reassigned between the groups.'
            ''
            'WHAT IS ONE PERMUTATION?'
            'One random shuffle of the pixels within an angular bin, followed by a comparison of the two medians. Each group keeps its original pixel count. Differences in either direction count. Iterations or draws means the number of shuffles.'
            'The p-value is the fraction of shuffles with a difference at least as large as the one observed. A smaller p-value means the observed difference is harder to reproduce by this shuffling process.'
            ''
            'HOW AUTO CHOOSES THE NUMBER'
            'Auto aims for 45,618 permutations per angular bin. That number comes from our target of an approximately +/-0.002 simulation interval near p = 0.05, when time allows.'
            'For a p-value near 0.050, this means aiming for a 95% simulation interval roughly 0.048-0.052. The 0.002 setting controls calculation precision; 0.05 is still the significance threshold.'
            'Auto first times a short trial, then chooses how many shuffles fit the runtime budget. Fast bins usually reach 45,618. Slower bins may use fewer, with a minimum of 10,000. The 50,000 maximum is a ceiling, not the target.'
            'So yes: if there is enough time, Auto often uses the same 45,618 count in every bin. It chooses the count before calculating the final p-value; it does not keep checking whether that p-value has stabilized.'
            'The runtime budget covers the comparison and is approximate. The 10,000 minimum can make a run exceed it. More pixels can make each shuffle slower and reduce the count that fits the budget.'
            'Manual uses exactly your entered count in every tested bin. Parallel CPU can use up to four workers to speed things up.'
            ''
            'WHAT THE SIMULATION INTERVAL MEANS'
            'How precisely have we calculated the p-value using this many shuffles? The interval describes uncertainty from a limited number of shuffles, with the observed eyes held fixed.'
            'Example: 480 out of 10,000 shuffles match or exceed the observed difference. The p-value is 480 / 10,000 = 0.048, with a 95% simulation interval of about 0.044-0.052.'
            'Because that interval includes 0.05, an orange marker flags that the calculation has not clearly resolved which side of the threshold the p-value lies on. More shuffles generally narrow the interval, but can move the estimated p-value either up or down.'
            'This is calculation uncertainty. For uncertainty from sampling different eyes, use the whole-eye bootstrap band in Median Profiles.'
            ''
            'READING THE PLOT'
            'Blue steps: p-value for each full angular bin. Light ribbons: bins with p < 0.05.'
            'Gray bars: optional 95% simulation intervals. Orange markers: intervals that include 0.05, even when the bars are hidden.'
            'Focus near p = 0.05 zooms the scale so small intervals are easier to see. Use the median profiles to judge how large the treatment difference is.'
            ''
            'KEEP IN MIND'
            'This is the retained pixel-shuffling test. Pixels from one eye are related, but the test treats them separately; p-values can therefore look more convincing than the number of eyes supports. More shuffles improve calculation precision, not the amount of biological evidence.'
            'Each angle is tested separately. Testing many angles or group pairs increases the chance of false-positive findings; the displayed p-values are not adjusted for this.'
            'A p-value above 0.05 does not establish that treatments are equivalent. A displayed zero means no shuffle reached the observed difference; its simulation interval still has a positive upper limit.'
            'If you need a more precise run, choose the larger count before rerunning. The fixed seed makes the same inputs and Manual count repeatable.'
            ''
            'RESULTS AND EXPORTS'
            'Angle: bin center. Iterations: shuffles used. Exceedances: shuffles matching or exceeding the observed difference. LegacyP: saved column name for Exceedances / Iterations. MC95L/U: simulation interval endpoints. NearThreshold: interval includes 0.05.'
            'Changing inputs clears completed results. Cancel discards partial results. Export Results saves CSV/MAT; Export Figure saves PDF.'};
    otherwise
        error('RpEGEN:Help','Unknown help topic: %s',topic);
end
end
